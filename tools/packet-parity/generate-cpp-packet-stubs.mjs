#!/usr/bin/env node

/**
 * Generate TypeScript packet stubs for C++ GameNetworkMessage classes that
 * do not yet have packet interfaces in `packages/protocol/src/swg/messages`.
 *
 * Source of truth:
 * - `packages/protocol/src/swg/messages/generated/cpp-packet-manifest.ts`
 */

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..', '..');

const MANIFEST_FILE = path.resolve(
  REPO_ROOT,
  'packages/protocol/src/swg/messages/generated/cpp-packet-manifest.ts'
);
const OUTPUT_FILE = path.resolve(
  REPO_ROOT,
  'packages/protocol/src/swg/messages/cpp-packet-stubs.ts'
);

const RESERVED_INTERFACE_NAMES = new Set([
  'CppPacketStubFieldMetadata',
  'CppPacketStubDefinition',
  'CppPacketStubByName',
]);

function parseManifestArray(tsText) {
  const startToken = 'export const CPP_PACKET_DEFINITIONS: CppPacketDefinition[] = ';
  const endToken = '\n\nexport const CPP_PACKET_DEFINITIONS_BY_NAME';
  const start = tsText.indexOf(startToken);
  if (start < 0) {
    throw new Error(`Unable to find CPP_PACKET_DEFINITIONS in ${MANIFEST_FILE}`);
  }
  const jsonStart = start + startToken.length;
  const end = tsText.indexOf(endToken, jsonStart);
  if (end < 0) {
    throw new Error(`Unable to find end of CPP_PACKET_DEFINITIONS in ${MANIFEST_FILE}`);
  }
  const raw = tsText.slice(jsonStart, end).trim();
  const jsonText = raw.endsWith(';') ? raw.slice(0, -1).trim() : raw;
  return JSON.parse(jsonText);
}

function escapeString(value) {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

function isValidIdentifier(name) {
  return /^[$A-Za-z_][$0-9A-Za-z_]*$/.test(name);
}

function formatFieldName(name) {
  if (isValidIdentifier(name)) {
    return name;
  }
  return `"${escapeString(name)}"`;
}

function formatFieldType(tsType) {
  if (!tsType || typeof tsType !== 'string') {
    return 'unknown';
  }
  return tsType;
}

function formatTsTypeLiteral(value) {
  return `"${escapeString(value)}"`;
}

function toRepoRelative(filePath) {
  return path.relative(REPO_ROOT, filePath).replace(/\\/g, '/');
}

async function readExistingStubNames() {
  try {
    const text = await fs.readFile(OUTPUT_FILE, 'utf8');
    const names = new Set();
    for (const match of text.matchAll(/export interface\s+([A-Za-z_][A-Za-z0-9_]*)\s*\{/g)) {
      const name = match[1];
      if (!RESERVED_INTERFACE_NAMES.has(name)) {
        names.add(name);
      }
    }
    return names;
  } catch (error) {
    if (error && typeof error === 'object' && 'code' in error && error.code === 'ENOENT') {
      return new Set();
    }
    throw error;
  }
}

async function main() {
  const manifestText = await fs.readFile(MANIFEST_FILE, 'utf8');
  const allPacketDefs = parseManifestArray(manifestText);
  const existingStubNames = await readExistingStubNames();
  const packetDefs = allPacketDefs
    .filter(
      (packet) =>
        !packet.implementedInTypescript || existingStubNames.has(packet.name)
    )
    .sort((a, b) => a.name.localeCompare(b.name));

  const lines = [];
  lines.push('/**');
  lines.push(' * AUTO-GENERATED FILE. DO NOT EDIT.');
  lines.push(' *');
  lines.push(' * Generated by:');
  lines.push(` * \`${toRepoRelative(path.join(SCRIPT_DIR, 'generate-cpp-packet-stubs.mjs'))}\``);
  lines.push(' *');
  lines.push(' * This file intentionally provides packet-accurate TypeScript stubs');
  lines.push(' * for C++ GameNetworkMessage classes that are still behavior-incomplete.');
  lines.push(' */');
  lines.push('');
  lines.push('export interface CppPacketStubFieldMetadata {');
  lines.push('  name: string;');
  lines.push('  archiveContainer: string;');
  lines.push('  cppType: string;');
  lines.push('  tsType: string;');
  lines.push("  source: 'addVariable' | 'declarationOnly';");
  lines.push('}');
  lines.push('');
  lines.push('export interface CppPacketStubDefinition {');
  lines.push('  name: string;');
  lines.push('  swgCrc32: string;');
  lines.push('  headers: string[];');
  lines.push('  fieldCount: number;');
  lines.push('  fields: CppPacketStubFieldMetadata[];');
  lines.push('  serializedLength: {');
  lines.push("    kind: 'exact' | 'min' | 'unknown';");
  lines.push('    exactBytes: number | null;');
  lines.push('    minBytes: number | null;');
  lines.push('  };');
  lines.push('}');
  lines.push('');
  lines.push('export const CppPacketStubOpcodes = {');
  for (const packet of packetDefs) {
    lines.push(`  ${packet.name}: ${packet.swgCrc32},`);
  }
  lines.push('} as const;');
  lines.push('');
  lines.push('export type CppPacketStubOpcodeName = keyof typeof CppPacketStubOpcodes;');
  lines.push('');

  for (const packet of packetDefs) {
    lines.push(`export interface ${packet.name} {`);
    lines.push(`  opcode: typeof CppPacketStubOpcodes.${packet.name};`);

    for (const field of packet.fields) {
      const fieldName = formatFieldName(field.name);
      const fieldType = formatFieldType(field.tsType);
      lines.push(
        `  /** C++: ${field.archiveContainer}<${field.cppType}> (${field.source}) */`
      );
      lines.push(`  ${fieldName}: ${fieldType};`);
    }

    lines.push('}');
    lines.push('');
  }

  lines.push('export type CppPacketStubMessage =');
  if (packetDefs.length === 0) {
    lines.push('  never;');
  } else {
    for (let i = 0; i < packetDefs.length; i += 1) {
      const packet = packetDefs[i];
      const suffix = i === packetDefs.length - 1 ? ';' : ' |';
      lines.push(`  ${packet.name}${suffix}`);
    }
  }
  lines.push('');

  lines.push('export interface CppPacketStubByName {');
  for (const packet of packetDefs) {
    lines.push(`  ${packet.name}: ${packet.name};`);
  }
  lines.push('}');
  lines.push('');

  lines.push('export const CPP_PACKET_STUB_DEFINITIONS: CppPacketStubDefinition[] = [');
  for (const packet of packetDefs) {
    lines.push('  {');
    lines.push(`    name: "${escapeString(packet.name)}",`);
    lines.push(`    swgCrc32: "${escapeString(packet.swgCrc32)}",`);
    lines.push(
      `    headers: [${packet.headers.map((header) => `"${escapeString(header)}"`).join(', ')}],`
    );
    lines.push(`    fieldCount: ${packet.fieldCount},`);
    lines.push('    fields: [');
    for (const field of packet.fields) {
      lines.push('      {');
      lines.push(`        name: "${escapeString(field.name)}",`);
      lines.push(`        archiveContainer: "${escapeString(field.archiveContainer)}",`);
      lines.push(`        cppType: "${escapeString(field.cppType)}",`);
      lines.push(`        tsType: ${formatTsTypeLiteral(field.tsType)},`);
      lines.push(`        source: "${escapeString(field.source)}",`);
      lines.push('      },');
    }
    lines.push('    ],');
    lines.push('    serializedLength: {');
    lines.push(`      kind: "${packet.serializedLength.kind}",`);
    lines.push(`      exactBytes: ${packet.serializedLength.exactBytes ?? 'null'},`);
    lines.push(`      minBytes: ${packet.serializedLength.minBytes ?? 'null'},`);
    lines.push('    },');
    lines.push('  },');
  }
  lines.push('];');
  lines.push('');
  lines.push(
    'export const CPP_PACKET_STUB_DEFINITIONS_BY_NAME = new Map<string, CppPacketStubDefinition>('
  );
  lines.push('  CPP_PACKET_STUB_DEFINITIONS.map((definition) => [definition.name, definition])');
  lines.push(');');
  lines.push('');

  await fs.writeFile(OUTPUT_FILE, `${lines.join('\n')}\n`, 'utf8');
  console.log(`Wrote ${toRepoRelative(OUTPUT_FILE)} with ${packetDefs.length} packet stubs`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.stack ?? error.message : String(error));
  process.exitCode = 1;
});
